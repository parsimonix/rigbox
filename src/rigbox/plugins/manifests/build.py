"""Turn a manifest into a pydantic model (via generated source) and a `construct` binary codec."""

from __future__ import annotations

import sys
import types
from typing import Any

import construct
from pydantic import BaseModel

from rigbox.plugins.manifests.schema import INT_RANGES, FieldSpec, StructManifest


def _kwargs(d: dict[str, Any]) -> str:
    """Format `d` as the keyword arguments of a call, e.g. ``ge=0, le=255``."""
    return ", ".join(f"{k}={v!r}" for k, v in d.items())


def _annotation(f: FieldSpec) -> str:
    """Source text of the field's type, with validation constraints."""
    base = {"string": "str", "bytes": "bytes", "bool": "bool", "f32": "float", "f64": "float"}.get(f.type, "int")
    item: dict[str, Any] = {}
    if f.type in INT_RANGES:
        item = dict(zip(("ge", "le"), INT_RANGES[f.type], strict=True))
    elif f.type == "string":
        item = {"max_length": f.length}
    elif f.type == "bytes":
        item = {"min_length": f.length, "max_length": f.length}

    constraints: dict[str, Any]
    if f.count is None:
        ann = base
        constraints = dict(item)
    else:
        element = f"Annotated[{base}, Field({_kwargs(item)})]" if item else base
        ann = f"list[{element}]"
        constraints = {"min_length": f.count, "max_length": f.count}
    if f.description:
        constraints["description"] = f.description
    if f.unit:
        constraints["json_schema_extra"] = {"unit": f.unit}
    return f"Annotated[{ann}, Field({_kwargs(constraints)})]" if constraints else ann


def model_source(m: StructManifest) -> str:
    """Return Python source for the manifest's pydantic model.

    Safe to exec: names are validated identifiers and every free-text value is emitted through repr().
    """
    lines = [
        f"# Generated by rigbox from manifest '{m.name}'. Do not edit.",
        "from typing import Annotated",
        "",
        "from pydantic import BaseModel, ConfigDict, Field",
        "",
        "",
        f"class {m.name}(BaseModel):",
        f"    {(m.description or m.name + ' packet.')!r}",
        '    model_config = ConfigDict(extra="forbid")',
    ]
    lines += [f"    {f.name}: {_annotation(f)}" for f in m.fields]
    return "\n".join(lines) + "\n"


def build_model(m: StructManifest) -> type[BaseModel]:
    """Build and return the pydantic model class for `m`."""
    # pydantic resolves annotations through sys.modules[cls.__module__], so run the source in a real module
    module = types.ModuleType(f"rigbox_manifest_{m.name}")
    sys.modules[module.__name__] = module
    exec(compile(model_source(m), f"<manifest {m.name}>", "exec"), module.__dict__)
    return getattr(module, m.name)


def _scalar(t: str, endian: str) -> Any:  # noqa: ANN401 - `construct` is untyped
    """Return the `construct` scalar type for manifest type `t`."""
    e = "l" if endian == "little" else "b"
    if t in INT_RANGES:
        return getattr(construct, f"Int{t[1:]}{'u' if t[0] == 'u' else 's'}{e}")
    if t in ("f32", "f64"):
        return getattr(construct, f"Float{t[1:]}{e}")
    return construct.Flag  # bool


def build_codec(m: StructManifest) -> construct.Struct:
    """Build the `construct` struct that packs and unpacks `m`'s packets."""
    parts = []
    for f in m.fields:
        if f.type == "string":
            ctype = construct.PaddedString(f.length, "utf8")
        elif f.type == "bytes":
            ctype = construct.Bytes(f.length)
        else:
            ctype = _scalar(f.type, m.endian)
            if f.count is not None:
                ctype = construct.Array(f.count, ctype)
        parts.append(f.name / ctype)
    return construct.Struct(*parts)
